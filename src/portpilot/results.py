"""`portpilot results`: one table over many `portpilot port` output directories.

Every number comes from the run.json the port run wrote (build attempts, fixes, patch size,
QNX test results), so the table can be regenerated and checked against the logs.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

_STAT = re.compile(r"(\d+) insertions?\(\+\)|(\d+) deletions?\(-\)")


def patch_lines(stat: str) -> int:
    """Changed lines (+ and -) from a `git diff --shortstat` line."""
    return sum(int(a or b) for a, b in _STAT.findall(stat or ""))


def _fixes(run: dict[str, Any]) -> list[dict[str, Any]]:
    return [*run.get("pre_fixes", []),
            *(f for a in run.get("attempts", []) for f in a.get("applied", [])),
            *(f for t in run.get("test_rounds") or [] for f in t.get("fixes", []))]


def row(out: Path) -> dict[str, Any]:
    run: dict[str, Any] = json.loads((out / "run.json").read_text(encoding="utf-8"))
    fixes = _fixes(run)
    rules = sorted({f["rule"] for f in fixes if f.get("rule")})
    ai = [f for f in fixes if str(f.get("rule", "")).startswith("ai")]
    tt = run.get("target_tests") or {}
    return {"library": run["name"], "ref": run.get("commit", ""), "built": bool(run.get("ok")),
            "attempts": len(run.get("attempts", [])), "fixes": len(fixes), "rules": rules,
            "ai_fixes": len(ai), "ai_proposals": len(run.get("ai") or []),
            "ai_accepted": sum(a.get("result") == "accepted" for a in run.get("ai") or []),
            "patch_lines": patch_lines(run.get("patch_stat", "")),
            "minutes": round(run.get("elapsed_s", 0) / 60, 1),
            "test_programs": [tt["passed"], tt["total"]] if tt else None,
            "test_cases": tt.get("cases") if tt else None,
            "services": tt.get("services", []) if tt else [],
            "stopped": run.get("stopped", "")}


def collect(dirs: list[Path]) -> list[dict[str, Any]]:
    """Rows for every directory that holds a run.json (given directly or one level down)."""
    outs: list[Path] = []
    for d in dirs:
        if (d / "run.json").is_file():
            outs.append(d)
        else:
            outs += sorted(p.parent for p in d.glob("*/run.json"))
    return [row(o) for o in outs]


def _tests(r: dict[str, Any]) -> str:
    if not r["test_programs"]:
        return "not run"
    p, n = r["test_programs"]
    s = f"{p}/{n} programs"
    if r["test_cases"]:
        s = f"{r['test_cases'][0]}/{r['test_cases'][1]} cases ({s})"
    return s


def to_markdown(rows: list[dict[str, Any]]) -> str:
    built = sum(r["built"] for r in rows)
    tested = [r for r in rows if r["test_programs"]]
    out = [f"{built}/{len(rows)} libraries built for QNX 8.0 from their upstream release; "
           f"{len(tested)} tested on a QNX 8.0 QEMU target.", "",
           "| Library | Release | Built | Build attempts | Fixes (AI) | Patch lines | "
           "Tests on QNX | Time |",
           "|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: r["library"].lower()):
        out.append(f"| {r['library']} | `{r['ref']}` | {'yes' if r['built'] else 'no'} | "
                   f"{r['attempts']} | {r['fixes']} ({r['ai_fixes']}) | {r['patch_lines']} | "
                   f"{_tests(r)} | {r['minutes']} min |")
    asked = sum(r["ai_proposals"] for r in rows)
    if asked:
        ok = sum(r["ai_accepted"] for r in rows)
        out += ["", f"Local AI: {asked} proposals, {ok} accepted (verified by rebuild or "
                f"retest), {asked - ok} rejected and reverted."]
    out += ["", "Fixes count every change PortPilot applied (rules, dependency ports, AI); "
            "patch lines are the source lines in `patches/qnx.patch`. Generated by "
            "`portpilot results` from each run's `run.json`.", ""]
    return "\n".join(out)
