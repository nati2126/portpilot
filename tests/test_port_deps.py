from pathlib import Path

import pytest

from portpilot import deps
from portpilot.diagnostics import parse
from portpilot.port import _build_deps


def test_a_missing_test_framework_header_builds_its_official_port(
        tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """libcoap's tests include <CUnit/CUnit.h>; build-files has a cunit port."""
    calls = []

    def fake(pkg: str, *a: object, **k: object) -> tuple[str, str]:
        calls.append(pkg)
        return "cunit", ""

    monkeypatch.setattr(deps, "ensure_port", fake)
    errs = parse("tests/testdriver.c:13:10: fatal error: CUnit/CUnit.h: No such file or "
                 "directory\n").errors
    built = _build_deps(errs, set(), tmp_path, {}, tmp_path, tmp_path, "x86_64", 4,
                        lambda s: None)
    assert calls == ["CUnit"]
    assert [(p, f.rule_id, f.path) for p, f in built] == [("cunit", "dep-official-port",
                                                            "CUnit")]


def test_stage_headers_port_installs_none(tmp_path: Path) -> None:
    # cunit's port installs with `make install-exec`: libcunit.so but no <CUnit/CUnit.h>;
    # CUnit.h is generated by configure in the build folder, the rest is in the source
    from portpilot.deps import stage_headers
    src, build, stage = tmp_path / "cunit", tmp_path / "nto-x86_64-o", tmp_path / "stage"
    (src / "CUnit" / "Headers").mkdir(parents=True)
    (src / "CUnit" / "Headers" / "CUnit.h.in").write_text("@VERSION@")
    (src / "CUnit" / "Headers" / "Basic.h").write_text("basic")
    (build / "CUnit" / "Headers").mkdir(parents=True)
    (build / "CUnit" / "Headers" / "CUnit.h").write_text("generated")
    got = stage_headers("CUnit/CUnit.h", stage, [src, build])
    inc = stage / "usr" / "include" / "CUnit"
    assert sorted(p.name for p in got) == ["Basic.h", "CUnit.h"]
    assert (inc / "CUnit.h").read_text() == "generated"
    assert stage_headers("CUnit/CUnit.h", stage, [src, build]) == []  # already there
